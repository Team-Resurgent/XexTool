u8   EmuXorValPatchA[] = {
	// entrypoint = r31,  entrypoint_xored = r25
	// kernelthunk = r3,  kernelthunk_xored= r24
	// retail entrypoint xor = 0xA8FC57AB
	// retail kernelthunk xor= 0x5B6D40B6
	// devkit entrypoint xor = 0x94859D4B ^ 0xA8FC57AB = 0x3C79CAE0
	// devkit kernelthunk xor= 0xEFB1F152 ^ 0x5B6D40B6 = 0xB4DCB1E4
	
	0x6F, 0xF9, 0xA8, 0xFC,	// xoris %r25, %r31, 0xA8FC	// 1st part of retail entry point xor
	0x6C, 0x78, 0x5B, 0x6D, // xoris %r24, %r3,  0x5B6D	// 1st part of retail kernel thunk xor
	0x3D, 0x00, 0x10, 0x00,	// lis %r8, 0x1000
	0x6B, 0x39, 0x57, 0xAB,	// xori  %r25, %r25, 0x57AB	// 2nd part of retail entry point xor
	0x6B, 0x18, 0x40, 0xB6,	// xori  %r24, %r24, 0x40B6	// 2nd part of retail kernel thunk xor
	0x7F, 0x19, 0x40, 0x40,	// cmplw cr6, %r25, %r8		// if(entrypoint_xored > 0x10000000)
	0x40, 0x99, 0x00, 0x14,	// ble cr6, xor_done		// {
	0x6F, 0x39, 0x3C, 0x79,	// xoris %r25, %r25, 0x3C79	//   1st part of devkit entry point xor
	0x6F, 0x18, 0xB4, 0xDC,	// xoris %r24, %r24, 0xB4DC	//   1st part of devkit kernel thunk xor
	0x6B, 0x39, 0xCA, 0xE0,	// xori  %r25, %r25, 0xCAE0	//   2nd part of devkit entry point xor
	0x6B, 0x18, 0xB1, 0xE4,	// xori  %r24, %r24, 0xB1E4	//   2nd part of devkit kernel thunk xor
	// xor_done:				// }
	0x3B, 0x60, 0x00, 0x01,	// li  %r27, 1				// li one, 1
	0x48, 0x00, 0x01, 0x18,	// b   verified_ok			// jump to after sig check
};
