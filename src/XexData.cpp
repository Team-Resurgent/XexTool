void XexData::prepareAllKeys()
{
	if(m_inited)
		return;
	prepareKey(XEX_MAGIC,				sizeof(XEX_MAGIC));
	prepareKey(XEX_RETAIL_KEY,			sizeof(XEX_RETAIL_KEY));
	prepareKey(XEX_DEBUG_KEY,			sizeof(XEX_DEBUG_KEY));
	prepareKey(XEX_MFG_RETAIL_KEY,		sizeof(XEX_MFG_RETAIL_KEY));
	prepareKey(XEX_MFG_DEBUG_KEY,		sizeof(XEX_MFG_DEBUG_KEY));
	prepareKey(XEX_SALT_XEX,			sizeof(XEX_SALT_XEX));
	prepareKey(XEX_SALT_REV,			sizeof(XEX_SALT_REV));
	prepareKey(XEX_RETAIL_PUBLIC_KEY,	sizeof(XEX_RETAIL_PUBLIC_KEY));
	prepareKey(XEX_DEBUG_PUBLIC_KEY,	sizeof(XEX_DEBUG_PUBLIC_KEY));
	prepareKey(XEX_RETAIL_PRIVATE_KEY,	sizeof(XEX_RETAIL_PRIVATE_KEY));
	prepareKey(XEX_DEBUG_PRIVATE_KEY,	sizeof(XEX_DEBUG_PRIVATE_KEY));
	m_inited = true;
}

void XexData::prepareKey(void* data, s32 size)
{
	u8* data_ptr = (u8*)data;
	u8 xor_val = 0xFF;
	for(s32 i=0; i<size; i++)
	{
		*data_ptr++ ^= xor_val--;
	}
}

